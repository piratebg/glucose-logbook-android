package com.biotrack.app

import android.content.ContentValues
import android.content.Context
import android.database.sqlite.SQLiteDatabase
import android.database.sqlite.SQLiteOpenHelper
import java.security.MessageDigest
import java.time.ZoneId
import java.util.UUID

data class Reading(val id: String, val mmol: Double, val time: Long, val source: String, val note: String, val exported: Boolean, val eligible: Boolean, val timeConfirmed: Boolean, val mealTag: String="", val userNote: String="")

class ReadingStore(context: Context, name: String = "biotrack.db") : SQLiteOpenHelper(context, name, null, 2) {
    override fun onCreate(db: SQLiteDatabase) {
        db.execSQL("CREATE TABLE readings(id TEXT PRIMARY KEY, mmol REAL, time INTEGER NOT NULL, source TEXT NOT NULL, note TEXT NOT NULL, exported INTEGER NOT NULL DEFAULT 0, eligible INTEGER NOT NULL, confirmed INTEGER NOT NULL, raw BLOB, local_time TEXT, sequence INTEGER, original_value REAL, original_unit TEXT, status INTEGER)")
        db.execSQL("CREATE TABLE checkpoints(device TEXT PRIMARY KEY, sequence INTEGER NOT NULL)")
        db.execSQL("CREATE TABLE contexts(device TEXT NOT NULL, sequence INTEGER NOT NULL, payload BLOB NOT NULL, received INTEGER NOT NULL, PRIMARY KEY(device,sequence,payload))")
        addAnnotations(db)
    }
    private fun addAnnotations(db: SQLiteDatabase) {
        db.execSQL("ALTER TABLE readings ADD COLUMN meal_tag TEXT NOT NULL DEFAULT ''")
        db.execSQL("ALTER TABLE readings ADD COLUMN user_note TEXT NOT NULL DEFAULT ''")
        // Only migrate explicit manual-entry tags generated by the old entry form.
        db.rawQuery("SELECT id,note FROM readings WHERE source='Manual'",null).use { c ->
            while(c.moveToNext()) {
                val note=c.getString(1)
                val prefix=note.substringBefore(" · ")
                val tag=prefix.takeIf { it in GlucoseAnalysis.MEAL_TAGS } ?: ""
                val detail=if(tag.isEmpty()) note else if(note==tag) "" else note.substringAfter(" · ")
                db.update("readings",ContentValues().apply { put("meal_tag",tag); put("user_note",detail) },"id=?",arrayOf(c.getString(0)))
            }
        }
    }
    override fun onUpgrade(db: SQLiteDatabase, oldVersion: Int, newVersion: Int) { if(oldVersion<2) addAnnotations(db) }
    @Synchronized fun save(device: String, packet: MeterReading): Boolean {
        // Packet identity includes meter, sequence, original time and original payload. Never use value/time alone.
        val identity = device + ":" + packet.raw.joinToString("") { "%02x".format(it.toInt() and 255) }
        val id = MessageDigest.getInstance("SHA-256").digest(identity.toByteArray()).joinToString("") { "%02x".format(it.toInt() and 255) }
        val local = packet.localTime.plusMinutes((packet.timeOffset ?: 0).toLong())
        val values = ContentValues().apply {
            put("id", id); put("mmol", packet.mmol); put("time", local.atZone(ZoneId.systemDefault()).toInstant().toEpochMilli())
            put("source", device); put("note", if (packet.eligible) "Meter time interpreted in phone timezone; confirm before sharing" else "Flagged or non-patient reading; excluded from summaries and sharing")
            put("eligible", if (packet.eligible) 1 else 0); put("confirmed", 0); put("raw", packet.raw)
            put("local_time", packet.localTime.toString()); put("sequence", packet.sequence)
            put("original_value", packet.originalValue); put("original_unit", packet.originalUnit); put("status", packet.status)
        }
        return writableDatabase.insertWithOnConflict("readings", null, values, SQLiteDatabase.CONFLICT_IGNORE) != -1L
    }
    @Synchronized fun manual(mmol: Double, note: String, mealTag: String="") {
        require(mmol.isFinite() && mmol > 0 && mmol <= 50)
        require(mealTag.isEmpty() || mealTag in GlucoseAnalysis.MEAL_TAGS)
        writableDatabase.insertOrThrow("readings", null, ContentValues().apply {
            put("id", UUID.randomUUID().toString()); put("mmol", mmol); put("time", System.currentTimeMillis())
            put("source", "Manual"); put("note", note); put("eligible", 1); put("confirmed", 1)
            put("user_note",note); put("meal_tag",mealTag)
        })
    }
    @Synchronized fun readings(): List<Reading> = readableDatabase.rawQuery("SELECT id,mmol,time,source,note,exported,eligible,confirmed,meal_tag,user_note FROM readings WHERE mmol IS NOT NULL ORDER BY time DESC", null).use { c ->
        buildList { while(c.moveToNext()) add(Reading(c.getString(0), c.getDouble(1), c.getLong(2), c.getString(3), c.getString(4), c.getInt(5)==1, c.getInt(6)==1, c.getInt(7)==1,c.getString(8),c.getString(9))) }
    }
    @Synchronized fun annotate(id: String,mealTag: String,note: String) {
        require(mealTag.isEmpty() || mealTag in GlucoseAnalysis.MEAL_TAGS)
        require(note.length<=2000)
        writableDatabase.update("readings",ContentValues().apply { put("meal_tag",mealTag); put("user_note",note) },"id=?",arrayOf(id))
    }
    @Synchronized fun checkpoint(device: String): Int? = readableDatabase.rawQuery("SELECT sequence FROM checkpoints WHERE device=?", arrayOf(device)).use { if(it.moveToFirst()) it.getInt(0) else null }
    @Synchronized fun context(device: String, bytes: ByteArray) {
        require(bytes.size>=3) { "Truncated glucose context" }
        val sequence=(bytes[1].toInt() and 255) or ((bytes[2].toInt() and 255) shl 8)
        writableDatabase.insertWithOnConflict("contexts",null,ContentValues().apply {
            put("device",device); put("sequence",sequence); put("payload",bytes); put("received",System.currentTimeMillis())
        },SQLiteDatabase.CONFLICT_IGNORE)
    }
    @Synchronized fun complete(device: String, sequence: Int) {
        writableDatabase.insertWithOnConflict("checkpoints", null, ContentValues().apply { put("device", device); put("sequence", sequence) }, SQLiteDatabase.CONFLICT_REPLACE)
    }
    @Synchronized fun confirm(id: String) { writableDatabase.update("readings", ContentValues().apply { put("confirmed", 1) }, "id=?", arrayOf(id)) }
    @Synchronized fun exported(id: String) { writableDatabase.update("readings", ContentValues().apply { put("exported", 1) }, "id=?", arrayOf(id)) }
}
